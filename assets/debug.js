function buildLines() {
  const lines = document.getElementById("code-lines");
  const numbers = document.getElementById("code-numbers");
  const box = document.getElementById("analysis");
  if (!lines) return;

  LINES.forEach((item, i) => {
    const no = i + 1;
    const btn = document.createElement("button");
    btn.type = "button";
    btn.setAttribute("data-line", String(no));
    if (item.bad) btn.setAttribute("data-bad", "1");
    btn.textContent = item.text || " ";
    btn.addEventListener("click", () => show(no, btn));
    lines.appendChild(btn);
    numbers.textContent += no + "\n";
  });

  function show(line, btn) {
    lines.querySelectorAll("button").forEach((b) => b.setAttribute("aria-pressed", String(b === btn)));
    const info = LINES[line - 1];
    if (!info || !info.d) {
      box.dataset.tone = "ok";
      box.innerHTML = "<b>Строка " + line + " — пустая.</b><br>Разбор не требуется: это отбивка между частями задания.";
      return;
    }
    box.dataset.tone = info.bad ? "bad" : "ok";
    box.innerHTML = "<b>Строка " + line + " — " + info.tag + "</b><br>" + info.d;
  }
}

function buildQuiz() {
  const quiz = document.getElementById("quiz");
  const result = document.getElementById("quiz-result");
  if (!quiz) return;

  QUESTIONS.forEach((q, i) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "btn btn-ghost";
    btn.style.cssText = "justify-content:flex-start;text-align:left;white-space:normal;line-height:1.5;height:auto;padding:14px 16px;letter-spacing:0";
    btn.textContent = i + 1 + ". " + q.text;
    btn.addEventListener("click", () => {
      result.hidden = false;
      result.dataset.tone = q.ok ? "ok" : "bad";
      result.innerHTML = "<b>" + (q.ok ? "Верно." : "Не лучший вариант.") + "</b> " + q.why;
      quiz.querySelectorAll("button").forEach((b) => (b.style.borderColor = ""));
      btn.style.borderColor = q.ok ? "var(--second)" : "#b4452c";
    });
    quiz.appendChild(btn);
  });
}

